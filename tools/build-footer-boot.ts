import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

export function serializeFooterBalance(source: string): string {
	return ts.transpileModule(source.replace(/^export /gm, ''), {
		compilerOptions: { target: ts.ScriptTarget.ES2022, removeComments: true },
	}).outputText.trim();
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	const source = readFileSync(new URL('../packages/ui/src/layout/footer-balance.ts', import.meta.url), 'utf8');
	const target = new URL('../packages/ui/src/head/footer-balance-source.ts', import.meta.url);
	writeFileSync(target, '// Generated by bun tools/build-footer-boot.ts.\nexport const footerBalanceBootSource = '
		+ JSON.stringify(serializeFooterBalance(source)) + ';\n');
	const bootModule = new URL('../packages/ui/src/head/boot.ts', import.meta.url);
	const { themeBootScript } = await import(bootModule.href) as { themeBootScript: string };
	const manifest = new URL('../packages/ui/src/head/boot.json', import.meta.url);
	const boot = JSON.parse(readFileSync(manifest, 'utf8'));
	boot.hash = `sha256-${createHash('sha256').update(themeBootScript).digest('base64')}`;
	writeFileSync(manifest, JSON.stringify(boot, null, '\t') + '\n');
}
